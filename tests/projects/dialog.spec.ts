for (const width of [320, 375, 430, 768, 1024, 1440, 1920]) {
  test(`dialog scrolls independently and keeps Close accessible at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 812 })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.goto('/')
    await page.getByRole('button', { name: 'View details: NexTick' }).click()
    const modal = page.getByRole('dialog', { name: 'NexTick', exact: true })
    const body = modal.locator('.project-dialog-body')
    const close = modal.getByRole('button', { name: 'Close project details' })
    const bounds = (await modal.boundingBox())!
    expect(bounds.x).toBeGreaterThanOrEqual(0)
    expect(bounds.x + bounds.width).toBeLessThanOrEqual(width)
    expect(bounds.height).toBeLessThanOrEqual(812)
    if (width < 768) expect(bounds.height).toBe(812)
    expect(await body.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    const top = (await close.boundingBox())!.y
    await body.evaluate(element => { element.scrollTop = element.scrollHeight })
    expect(await body.evaluate(element => element.scrollTop)).toBeGreaterThan(0)
    await expect(modal.getByRole('link', { name: /Project documentation/ })).toBeInViewport()
    expect((await close.boundingBox())!.y).toBe(top)
    expect((await close.boundingBox())!.height).toBeGreaterThanOrEqual(44)
    await close.click()
    await expect(modal).toHaveCount(0)
  })
}

