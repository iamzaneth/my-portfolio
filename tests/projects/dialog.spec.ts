test('native focus containment, Escape, scroll restoration, and trigger focus work together', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  const trigger = page.getByRole('button', { name: 'View details: NexTick' })
  await trigger.scrollIntoViewIfNeeded()
  const before = await page.evaluate(() => ({ y: scrollY, style: document.body.style.cssText, url: location.href }))
  await trigger.click()
  const modal = page.getByRole('dialog')
  const close = modal.getByRole('button', { name: 'Close project details' })
  await expect(close).toBeFocused()
  await expect(page.locator('body')).toHaveCSS('position', 'fixed')
  const last = modal.getByRole('link', { name: /Project documentation/ })
  await last.focus()
  await page.keyboard.press('Tab')
  // Native dialogs allow browser chrome, while the underlying page stays inert.
  // https://www.w3.org/WAI/WCAG22/Techniques/html/H102
  if (!await page.evaluate(() => document.hasFocus())) await page.keyboard.press('Tab')
  await expect(close).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  if (!await page.evaluate(() => document.hasFocus())) await page.keyboard.press('Shift+Tab')
  await expect(last).toBeFocused()
  await page.locator('.contact-email').evaluate(element => (element as HTMLElement).focus())
  expect(await modal.evaluate(element => element.contains(document.activeElement))).toBe(true)
  await page.mouse.move(5, 5)
  await page.mouse.wheel(0, 700)
  expect(await page.evaluate(() => document.body.style.top)).toBe(`${-before.y}px`)
  expect(await page.evaluate(() => scrollY)).toBe(0)
  await page.keyboard.press('Escape')
  await expect(modal).toHaveCount(0)
  await expect(trigger).toBeFocused()
  const after = await page.evaluate(() => ({ y: scrollY, style: document.body.style.cssText, url: location.href }))
  expect(after).toEqual(before)
  await page.mouse.wheel(0, -150)
  await expect.poll(() => page.evaluate(() => scrollY)).toBeLessThan(before.y)
})

test('content clicks keep the dialog open; backdrop and Close both restore focus', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  const trigger = page.getByRole('button', { name: 'View details: NexTick' })
  await trigger.click()
  const modal = page.getByRole('dialog')
  await modal.getByRole('heading', { name: 'NexTick', exact: true }).click()
  await expect(modal).toBeVisible()
  // Padding belongs to the panel and must not be mistaken for the backdrop.
  await modal.click({ position: { x: 3, y: 100 } })
  await expect(modal).toBeVisible()
  await page.mouse.click(5, 5)
  await expect(modal).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await trigger.click()
  await modal.getByRole('button', { name: 'Close project details' }).click()
  await expect(modal).toHaveCount(0)
  await expect(trigger).toBeFocused()
})

