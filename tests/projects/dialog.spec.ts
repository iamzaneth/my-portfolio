test('short open/close motion and live reduced-motion changes leave no stale modal state', async ({ page }) => {
  await page.goto('/')
  const trigger = page.getByRole('button', { name: 'View details: NexTick' })
  await trigger.click()
  const modal = page.getByRole('dialog')
  await expect(modal).toHaveCSS('animation-name', 'project-dialog-enter')
  await modal.getByRole('button', { name: 'Close project details' }).click()
  await expect(modal).toHaveAttribute('data-closing', 'true')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(modal).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await trigger.click()
  await expect(modal).toHaveCSS('animation-name', 'none')
  await expect(modal).toHaveCSS('transform', 'none')
  await page.keyboard.press('Escape')
  await expect(modal).toHaveCount(0)
})
