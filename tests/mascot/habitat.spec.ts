import { expect, test } from '@playwright/test'

test('moon garden play feedback follows user intent and remains useful without motion', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await expect(page.locator('.garden-scenery')).toHaveAttribute('aria-hidden', 'true')
  const play = page.getByRole('button', { name: 'Play', exact: true })
  await play.click()
  await expect(play).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.cat-toy')).toHaveAttribute('data-active', 'true')
  await expect(page.locator('.cat-toy')).toHaveCSS('animation-name', 'none')
  await page.getByRole('button', { name: 'Nap', exact: true }).click()
  await expect(page.locator('.cat-toy')).toHaveAttribute('data-active', 'false')
  await expect(play).toHaveAttribute('aria-pressed', 'false')
  await expect(page.getByRole('button', { name: 'Wake', exact: true })).toBeVisible()
})

test('project discoveries expire and cannot displace a direct cat reaction', async ({ page }) => {
  await page.clock.install()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.getByRole('button', { name: 'View details: NexTick' }).click()
  await page.keyboard.press('Escape')
  await page.locator('#home').scrollIntoViewIfNeeded()
  await expect(page.locator('.cat-bubble')).toContainText('inside NexTick')
  await page.getByRole('button', { name: 'Pet', exact: true }).click()
  await expect(page.locator('.cat-bubble')).toContainText('hello')
  await page.clock.runFor(13000)
  await expect(page.locator('.cat-bubble')).toHaveText('Hi, I’m your pixel companion.')
})
