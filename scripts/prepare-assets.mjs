import sharp from 'sharp'
import { mkdir, copyFile, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'

// Optional rebuild: node scripts/prepare-assets.mjs <extracted Pet Cats Pack directory>
// The published asset pack is CC0. The original sheets are never fetched at runtime.
const source = process.argv[2]
if (source) {
  await mkdir('public/mascot', { recursive: true })
  const files = { idle: 'Idle', walk: 'Walk', run: 'Run', meow: 'Meow', sleep: 'Sleeping2', wake: 'Stretching', sit: 'Sitting', lieDown: 'Laying', groom: 'Licking 1', groomPaw: 'Licking 2', scratch: 'Itch' }
  const sheets = []
  const catalog = {}
  for (const [name, original] of Object.entries(files)) {
    const { data, info } = await sharp(path.join(source, 'Cat-1', `Cat-1-${original}.png`)).ensureAlpha().raw().toBuffer({ resolveWithObject: true })
    // Preserve the source luminance and alpha while moving its brown palette to lavender.
    for (let i = 0; i < data.length; i += 4) {
      if (!data[i + 3]) continue
      const light = (data[i] * 0.2126 + data[i + 1] * 0.7152 + data[i + 2] * 0.0722) / 255
      data[i] = Math.min(255, Math.round(64 + light * 210))
      data[i + 1] = Math.min(255, Math.round(43 + light * 180))
      data[i + 2] = Math.min(255, Math.round(104 + light * 220))
    }
    const frames = info.width / 50
    const cropped = []
    for (let frame = 0; frame < frames; frame++) {
      cropped.push({ input: await sharp(data, { raw: info }).extract({ left: frame * 50 + 9, top: 10, width: 32, height: 32 }).png().toBuffer(), left: frame * 32, top: 0 })
    }
    const sheet = await sharp({ create: { width: frames * 32, height: 32, channels: 4, background: '#00000000' } }).composite(cropped).png().toBuffer()
    await writeFile(`public/mascot/${name}.png`, sheet)
    catalog[name] = { row: sheets.length, frames }
    sheets.push({ input: sheet, left: 0, top: sheets.length * 32 })
  }
  const columns = Math.max(...Object.values(catalog).map(({ frames }) => frames))
  await sharp({ create: { width: columns * 32, height: sheets.length * 32, channels: 4, background: '#00000000' } }).composite(sheets).png().toFile('public/mascot/cat-atlas.png')
  await writeFile('src/features/mascot/catSprites.ts', `// Generated by scripts/prepare-assets.mjs from the licensed source sheets.\nexport const catAtlas = ${JSON.stringify({ columns, rows: sheets.length }, null, 2)} as const\n\nexport const catSprites = ${JSON.stringify(catalog, null, 2)} as const\n`)
  await copyFile(path.join(source, 'License.txt'), 'public/mascot/LICENSE.txt')
}

await sharp('assets/source/avatar.png').resize(256, 256, { fit: 'cover' }).webp({ quality: 82 }).toFile('public/avatar.webp')
const fontFiles = [
  ['@fontsource-variable/manrope/files/manrope-latin-wght-normal.woff2', 'manrope-latin.woff2'],
  ['@fontsource/ibm-plex-mono/files/ibm-plex-mono-latin-400-normal.woff2', 'ibm-plex-mono-latin.woff2'],
]
await mkdir('public/fonts', { recursive: true })
for (const [sourceFile, target] of fontFiles) await copyFile(`node_modules/${sourceFile}`, `public/fonts/${target}`)
for (const pkg of ['@fontsource-variable/manrope', '@fontsource/ibm-plex-mono']) {
  const license = await readFile(`node_modules/${pkg}/LICENSE`, 'utf8')
  await writeFile(`public/fonts/${pkg.includes('manrope') ? 'MANROPE' : 'IBM-PLEX-MONO'}-LICENSE.txt`, license)
}
console.log('Local fonts, optimized avatar, and mascot assets prepared.')
